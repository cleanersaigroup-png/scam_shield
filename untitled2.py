def analyze_url(message):

    urls = re.findall(
        r"(https?://[^\s]+|www\.[^\s]+)",
        message.lower()
    )

    if not urls:

        return {
            "found": False,
            "suspicious": False,
            "score": 0,
            "urls": [],
            "reasons": []
        }

    reasons = []
    suspicious = False

    for url in urls:

        clean_url = url.rstrip(".,!?)]}")

        # HTTP
        if clean_url.startswith("http://"):

            suspicious = True

            reasons.append(
                "The link does not use HTTPS."
            )

        # IP address URL
        if re.search(
            r"https?://\d{1,3}(\.\d{1,3}){3}",
            clean_url
        ):

            suspicious = True

            reasons.append(
                "The URL uses a raw IP address instead of a normal domain."
            )

        # URL shorteners
        shorteners = [
            "bit.ly",
            "tinyurl.com",
            "t.co",
            "goo.gl",
            "is.gd",
            "cutt.ly",
            "shorturl.at"
        ]

        if any(x in clean_url for x in shorteners):

            suspicious = True

            reasons.append(
                "The link uses a URL-shortening service."
            )

        # Suspicious words
        suspicious_words = [
            "verify",
            "verification",
            "login",
            "secure",
            "account",
            "kyc",
            "update",
            "refund",
            "reward",
            "claim",
            "wallet",
            "password"
        ]

        matches = [
            word for word in suspicious_words
            if word in clean_url
        ]

        if matches:

            suspicious = True

            reasons.append(
                "The URL contains sensitive-action keywords: "
                + ", ".join(matches)
            )

    score = 0

    if suspicious:
        score = min(90, 40 + len(reasons) * 10)

    return {
        "found": True,
        "suspicious": suspicious,
        "score": score,
        "urls": urls,
        "reasons": reasons
    }


