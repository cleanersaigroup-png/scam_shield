# ============================================================

def detect_language(text):

    if not text:
        return "Unknown"

    devanagari = len(
        re.findall(r"[\u0900-\u097F]", text)
    )

    english = len(
        re.findall(r"[A-Za-z]", text)
    )

    total = devanagari + english

    if total == 0:
        return "Unknown"

    if devanagari > 0 and english > 0:

        ratio_hindi = devanagari / total

        if ratio_hindi > 0.25:
            return "Hindi + English"

        return "Hinglish"

    if devanagari > 0:
        return "Hindi"

    return "English / Hinglish"


