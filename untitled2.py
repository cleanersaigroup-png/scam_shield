# RISK ENGINE
# ============================================================

def calculate_risk(
    ai_score,
    url_data,
    reputation_data,
    community_count,
    techniques
):

    signals = []
    weights = []

    # AI
    signals.append(ai_score)
    weights.append(0.70)


    # URL
    if url_data["found"]:

        signals.append(url_data["score"])
        weights.append(0.15)


    # Reputation
    if reputation_data["reports"] > 0:

        rep_score = min(
            90,
            reputation_data["reports"] * 10
        )

        signals.append(rep_score)
        weights.append(0.15)


    # Community
    if community_count > 0:

        community_score = community_risk_score(
            community_count
        )

        signals.append(community_score)
        weights.append(0.15)


    if not signals:

        return 0

    risk = sum(
        score * weight
        for score, weight in zip(signals, weights)
    ) / sum(weights)


   # Force higher risk when multiple scam techniques are detected

    if len(techniques) >= 3:
        risk = max(risk, 70)

    if len(techniques) >= 4:
        risk = max(risk, 85)

    return round(
        min(100, max(0, risk)),
        1
    )


