def model_prediction(message):

    if not MODEL_READY:

        return {
            "probability": 0,
            "prediction": "Unknown"
        }

    try:

        X = tfidf.transform([message])

        probability = model.predict_proba(X)[0]

        # Existing model assumed class 1 = scam
        scam_probability = float(probability[1])

        prediction = (
            "Scam"
            if scam_probability >= 0.5
            else "Likely Safe"
        )

        return {
            "probability": round(
                scam_probability * 100,
                2
            ),
            "prediction": prediction
        }

    except Exception as e:

        print("Prediction error:", e)

        return {
            "probability": 0,
            "prediction": "Unknown"
        }


