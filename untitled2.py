def normalize_phone(phone):

    if not phone:
        return ""

    digits = re.sub(r"\D", "", str(phone))

    # Indian numbers
    if len(digits) >= 10:
        return digits[-10:]

    return digits


# ============================================================
# PHONE REPUTATION
# ============================================================

def get_reputation(phone):

    phone = normalize_phone(phone)

    if not phone:
        return {
            "found": False,
            "reports": 0,
            "category": "Unknown"
        }

    try:
        df = pd.read_csv(REPUTATION_FILE)

        if df.empty:
            return {
                "found": False,
                "reports": 0,
                "category": "Unknown"
            }

        df["phone_number"] = (
            df["phone_number"]
            .astype(str)
            .apply(normalize_phone)
        )

        result = df[df["phone_number"] == phone]

        if result.empty:
            return {
                "found": False,
                "reports": 0,
                "category": "Unknown"
            }

        reports = int(result.iloc[0]["reports"])

        category = str(
            result.iloc[0].get("category", "Reported")
        )

        return {
            "found": True,
            "reports": reports,
            "category": category
        }

    except Exception as e:

        print("Reputation error:", e)

        return {
            "found": False,
            "reports": 0,
            "category": "Unknown"
        }


